/**
 * The liquid-glass stylesheet. Embedded as a template literal rather than a
 * JSON string because it is long, multi-line and full of `{`/`}`: escaping it
 * would make the shipped copy unreadable in the bundle, and there is nothing in
 * it that a template literal cannot carry. The guard below keeps that true.
 */
const GLASS_CSS = glassCss()
if (GLASS_CSS.includes('`') || GLASS_CSS.includes('${')) {
  throw new Error('glass CSS must not contain a backtick or ${ — it is embedded as a template literal')
}

