/**
 * Emits `lib/client.js` — the browser half — from `tools/tokens.json`.
 *
 * The client bundle is a plain `window.__ModuleLoader__.load({ factory })` CJS
 * module, which is what the DSH Loader's lazy module table expects. A theme
 * needs no bundler: it is assembled as text so the plugin stays installable
 * from a checkout with no build step.
 *
 * What it mounts:
 *
 *   1. **One token layer** — the palette as `{ light, dark }` pairs, folded over
 *      the active built-in theme with `ctx.theme.overrideTokens`. It is a layer,
 *      not a third-party theme id, because only light/dark/system are
 *      *preferences* the settings document keeps: `ThemeRuntime.adopt()`
 *      restores the stored preference whenever it lands, so an id selected at
 *      boot is session-scoped and gets reverted. Riding on the built-in
 *      preference is what makes "朱砂·深色" survive a restart.
 *   2. **A settings row** under Settings → General: an on/off switch, 浅色 /
 *      深色 chips, and an entrance-animation switch. The chips write the
 *      built-in preference, so the Appearance row above and this one are one
 *      choice, not two.
 *   3. **A liquid-glass layer**: the composer becomes a frosted pane (墨玻璃 /
 *      宣纸玻璃); the design system's own frosted menus are left alone.
 *   4. **An optional background layer**, off unless an image is supplied.
 *   5. **A first-load curtain** — surface colour, a cinnabar seal, a warm ink
 *      bloom, then it lifts. Once per page load; skipped under reduced motion.
 *
 * `localStorage` now holds only whether 朱砂 is on; the scheme lives in the
 * settings document. The old package's switch, and its pre-0.4 `choice` key,
 * are migrated once.
 */
